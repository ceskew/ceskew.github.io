// node tools/solve.js [levelIndex ...]  — search for a solution to each level with the real optics engine,
// and record it in solutions.js (used by the in-game "Reveal" and by verify.js).
const fs = require('fs'), path = require('path');
const { scene, D, dir, Optics, LEVELS } = require('./lib');
const { SB, NEED, TH } = Optics;
let seed = 12345; const rnd = () => (seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296;
const gauss = () => { let s = 0; for (let i = 0; i < 4; i++) s += rnd(); return (s - 2) * 1.7; };

function score(sc) {
  const out = [], P = Optics.build(sc), res = Optics.evaluate(sc, P, out);
  let s = 0, ok = true;
  sc.sensors.forEach((sen, i) => {
    const r = res[i]; ok = ok && r.ok;
    s += 10 * Math.min(1, r.fill) + Math.min(r.fill, 2.2) - 12 * Math.max(0, r.bad - 0.04);
    for (const b of NEED[sen.need]) {                      // shaping: pull each needed band toward the sensor
      if (r.frac[b] > 0.02) continue;
      let best = 1e9; const lo = SB[b][0], hi = SB[b][1];
      for (let k = 0; k < out.length; k += 6) {
        if (out[k + 4] < lo || out[k + 4] > hi) continue;
        const ax = out[k], ay = out[k + 1], ex = out[k + 2] - ax, ey = out[k + 3] - ay;
        let t = ((sen.x - ax) * ex + (sen.y - ay) * ey) / (ex * ex + ey * ey); t = t < 0 ? 0 : t > 1 ? 1 : t;
        const d = Math.hypot(ax + ex * t - sen.x, ay + ey * t - sen.y); if (d < best) best = d;
      }
      s -= Math.min(best, 1500) / 150;
    }
  });
  // keep the bench tidy: pieces apart from each other and from sensors / emitters
  const ps = sc.pieces;
  for (let i = 0; i < ps.length; i++) {
    for (let j = i + 1; j < ps.length; j++) { const d = Math.hypot(ps[i].x - ps[j].x, ps[i].y - ps[j].y); if (d < 170) s -= (170 - d) / 20; }
    for (const sen of sc.sensors) { const d = Math.hypot(ps[i].x - sen.x, ps[i].y - sen.y); if (d < 150 && ps[i].t !== 'source') s -= (150 - d) / 20; }
  }
  return { s, ok, res };
}

function solve(L, restarts, iters, fix) {
  const sc = scene(L), all = sc.pieces.filter(p => p.lock !== 'all');
  if (fix) all.forEach((p, i) => { if (fix[i]) { p.x = fix[i][0]; p.y = fix[i][1]; p.a = fix[i][2] * D; } });
  const mov = all.filter((p, i) => !(fix && fix[i]));
  if (!mov.length) { const c = score(sc); return { s: c.s, ok: c.ok, res: c.res, poses: fix }; }
  let bestAll = null;
  for (let r = 0; r < restarts; r++) {
    for (const p of mov) { if (p.lock !== 'pos') { p.x = 120 + rnd() * 1360; p.y = 130 + rnd() * 660; } p.a = rnd() * Math.PI * 2; }
    let cur = score(sc);
    for (let it = 0; it < iters; it++) {
      const f = 1 - it / iters, p = mov[(rnd() * mov.length) | 0], o = [p.x, p.y, p.a];
      const m = rnd();
      if (p.lock !== 'pos' && m < 0.6) { p.x = Math.min(1500, Math.max(100, p.x + gauss() * (3 + 160 * f * f))); p.y = Math.min(810, Math.max(120, p.y + gauss() * (3 + 160 * f * f))); }
      if (m > 0.4 || p.lock === 'pos') p.a += gauss() * (0.01 + 0.6 * f * f);
      const nx = score(sc);
      if (nx.s >= cur.s) cur = nx; else { p.x = o[0]; p.y = o[1]; p.a = o[2]; }
    }
    if (!bestAll || cur.s > bestAll.s) bestAll = { s: cur.s, ok: cur.ok, res: cur.res, poses: all.map(p => [+p.x.toFixed(1), +p.y.toFixed(1), +(((p.a / D) % 360 + 360) % 360).toFixed(2)]) };
    if (bestAll.ok && r >= 5) break;
  }
  return bestAll;
}

const SOL = globalThis.SOLUTIONS || {};
const fi = process.argv.indexOf('--fix'), FIX = fi > 0 ? JSON.parse(process.argv.splice(fi, 2)[1]) : null;
const which = process.argv.length > 2 ? process.argv.slice(2).map(Number) : LEVELS.map((_, i) => i);
for (const i of which) {
  const L = LEVELS[i], b = solve(L, 60, 2500, FIX || L.sol);
  console.log(i, L.name, b.ok ? 'SOLVED' : 'no solution', b.s.toFixed(2), JSON.stringify(b.poses), b.res.map(r => r.fill.toFixed(2) + (r.contam ? '!' : '')).join(' '));
  if (b.ok) SOL[L.name] = b.poses;
}
fs.writeFileSync(path.join(dir, 'solutions.js'), '/* Generated by tools/solve.js — one machine-found solution per level. */\n(typeof window !== "undefined" ? window : globalThis).SOLUTIONS = ' + JSON.stringify(SOL, null, 1) + ';\n');
